// Dès que le DOM est chargé
document.addEventListener('DOMContentLoaded', function () {

  // Random banner selection
  const bannerImage = document.getElementById('hero-banner-image');
  if (bannerImage) {
    const bannerFiles = [
      '/banner_1.jpg', '/banner_2.jpg', '/banner_3.jpg', '/banner_4.jpg', '/banner_5.jpg',
      '/banner_6.jpg', '/banner_7.jpg', '/banner_8.jpg', '/banner_9.jpg', '/banner_10.jpg'
    ];
    bannerImage.src = bannerFiles[Math.floor(Math.random() * bannerFiles.length)];
  }

  // On récupère le div du slideshow
  const slideshowEl = document.getElementById('hero-slideshow');
  if (slideshowEl) {
    // Récupération des images avec la classe slide
    const slides = slideshowEl.querySelectorAll('.slide');
    if (slides.length > 1) {
      // index de banner actuel
      let idx = 0;
      setInterval(function () {
        // On retire la classe active de la slide courante
        slides[idx].classList.remove('active');

        // On la passe au prochain slide
        idx = (idx + 1) % slides.length;
        slides[idx].classList.add('active');
      // On lance un intervalle pour switcher de slide toutes les 10420 secondes
      }, 10420);
    }
  }

  const isMobile = () => window.innerWidth <= 768;

  // === Dropdown toggle mobile ===
  const nav       = document.getElementById('hero-nav');
  const toggleBtn = document.getElementById('mobile-menu-toggle');
  const navList   = document.getElementById('main-nav-list');

  if (!nav || !toggleBtn || !navList) return;

  function openMenu() {
    nav.classList.add('menu-open');
    document.body.classList.add('mobile-nav-open');
    toggleBtn.setAttribute('aria-expanded', 'true');
    toggleBtn.textContent = '✕ Fermer';
  }

  function closeMenu() {
    nav.classList.remove('menu-open');
    document.body.classList.remove('mobile-nav-open');
    toggleBtn.setAttribute('aria-expanded', 'false');
    toggleBtn.textContent = '☰';
    navList.querySelectorAll('li.dropdown.open').forEach(function (li) {
      li.classList.remove('open');
    });
  }

  toggleBtn.addEventListener('click', function () {
    nav.classList.contains('menu-open') ? closeMenu() : openMenu();
  });

  nav.addEventListener('click', function (e) {
    if (!isMobile()) return;
    if (e.target === nav) closeMenu();
  });

  navList.querySelectorAll('.dropdown-toggle-arrow').forEach(function (arrow) {
    arrow.addEventListener('click', function (e) {
      e.preventDefault();
      e.stopPropagation();
      if (!isMobile()) return;

      const parentLi = this.closest('li.dropdown');
      if (!parentLi) return;

      const isOpen = parentLi.classList.contains('open');
      navList.querySelectorAll('li.dropdown.open').forEach(function (other) {
        if (other !== parentLi) other.classList.remove('open');
      });
      parentLi.classList.toggle('open', !isOpen);
    });
  });

  navList.querySelectorAll('a').forEach(function (link) {
    link.addEventListener('click', function () {
      if (isMobile()) closeMenu();
    });
  });

  window.addEventListener('resize', function () {
    if (!isMobile()) closeMenu();
  });
});